#!/bin/bash
#
# Builds the benchmark build of one implementation into
# bench/artifacts/<build>/<framework>/<platform>: a build that sends its
# searches to bench/mock-server.
#
#   ./scripts/build.sh <native|flutter|expo> <ios|android> [release|debug] [simulator|device]
#
# release (the default) is what the main results compare. debug builds every
# part the way a developer runs it day to day: Xcode's Debug configuration,
# Android's debug build type, Flutter in JIT mode, and React Native loading
# its JavaScript from Metro (start it with `npx expo start` in expo/app
# before measuring).
#
# iOS produces an app for the simulator, Android an APK (the release one is
# signed with the debug key and shrunk by R8), which is what run.mjs installs.
# Whatever each toolchain calls its product, it lands as App.app / app-*.apk.
#
# `device` builds iOS for a physical iPhone into <platform>-device/: signed
# with the team in BENCH_IOS_TEAM_ID, and searching the mock server on the
# Mac's LAN address (BENCH_IOS_DEVICE_API_BASE_URL overrides it), since an
# iPhone cannot reach the Mac's loopback. Flutter can then be built in
# release (AOT) mode. Android devices run the same APK as the emulator.

set -euo pipefail

FRAMEWORK="${1:?framework: native, flutter or expo}"
PLATFORM="${2:?platform: ios or android}"
BUILD="${3:-release}"
TARGET="${4:-simulator}"
case "$BUILD" in
  release | debug) ;;
  *)
    echo "build: release or debug" >&2
    exit 1
    ;;
esac
case "$TARGET" in
  simulator | device) ;;
  *)
    echo "target: simulator or device" >&2
    exit 1
    ;;
esac

# Xcode configurations and Gradle tasks spell it capitalized.
CONFIG="$(tr '[:lower:]' '[:upper:]' <<< "${BUILD:0:1}")${BUILD:1}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/bench/artifacts/$BUILD/$FRAMEWORK/$PLATFORM"

# The iOS simulator shares the host's network. The Android emulator reaches
# the mock server on its own loopback too: run.mjs sets up `adb reverse`,
# because going through the emulator's NAT (10.0.2.2) took 0.6-1 s a request.
IOS_API_BASE_URL="http://127.0.0.1:8787"
ANDROID_API_BASE_URL="http://127.0.0.1:8787"

IOS_SDK=iphonesimulator
IOS_DESTINATION='generic/platform=iOS Simulator'
IOS_SIGNING=(CODE_SIGNING_ALLOWED=NO)
if [[ "$PLATFORM" == "ios" && "$TARGET" == "device" ]]; then
  : "${BENCH_IOS_TEAM_ID:?set BENCH_IOS_TEAM_ID to the Apple Developer team that signs device builds}"
  OUT="$OUT-device"
  IOS_SDK=iphoneos
  IOS_DESTINATION='generic/platform=iOS'
  IOS_SIGNING=(-allowProvisioningUpdates DEVELOPMENT_TEAM="$BENCH_IOS_TEAM_ID" CODE_SIGN_STYLE=Automatic)
  IOS_API_BASE_URL="${BENCH_IOS_DEVICE_API_BASE_URL:-http://$(ipconfig getifaddr en0):8787}"
fi

# Builds an Xcode target and copies its .app into $OUT as App.app.
#
# Every implementation is called something else (App / Runner / the Expo
# app's name) and, with a custom Build Location in Xcode's settings (which
# -derivedDataPath does not override), they would all land in one products
# directory. Explicit SYMROOT / OBJROOT keep each build to itself.
build_ios_app() {
  local work_dir="$1" product="$2"
  shift 2
  local settings=(
    "$@"
    -configuration "$CONFIG"
    -sdk "$IOS_SDK"
    SYMROOT="$work_dir/build/Products"
    OBJROOT="$work_dir/build/Intermediates"
  )

  xcodebuild build "${settings[@]}" \
    -destination "$IOS_DESTINATION" \
    "${IOS_SIGNING[@]}" \
    -quiet

  local dir
  dir="$(xcodebuild "${settings[@]}" -showBuildSettings 2>/dev/null |
    sed -n 's/^ *TARGET_BUILD_DIR = //p' | head -1)"

  rm -rf "$OUT"
  mkdir -p "$OUT"
  ditto "$dir/$product.app" "$OUT/App.app"
}

copy_apk() {
  local apk="$1"
  rm -rf "$OUT"
  mkdir -p "$OUT"
  cp "$apk" "$OUT/app-$BUILD.apk"
}

# The Expo app's Xcode project is generated by `expo prebuild`, so its scheme
# is read back rather than hard-coded.
first_scheme() {
  xcodebuild -workspace "$1" -list -json |
    node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>console.log(JSON.parse(s).workspace.schemes[0]))'
}

case "$FRAMEWORK/$PLATFORM" in
  native/ios)
    (cd "$ROOT/native/ios" && xcodegen generate --quiet)
    build_ios_app "$ROOT/native/ios" NativeApp \
      -project "$ROOT/native/ios/NativeApp.xcodeproj" -scheme NativeApp \
      BENCH_API_BASE_URL="$IOS_API_BASE_URL"
    ;;
  native/android)
    (cd "$ROOT/native/android" &&
      ./gradlew "assemble$CONFIG" -PbenchApiBaseUrl="$ANDROID_API_BASE_URL" --quiet)
    copy_apk "$ROOT/native/android/app/build/outputs/apk/$BUILD/app-$BUILD.apk"
    ;;
  flutter/ios)
    # Flutter has no release (AOT) build for the simulator: the simulator
    # slice of the AOT engine holds no Dart code. The simulator therefore
    # always runs the debug (JIT) build, whichever build this is asked for.
    # See flutter/README.md; the device results have the release numbers.
    mode=debug
    [[ "$TARGET" == "device" ]] && mode="$BUILD"
    simulator=(--simulator)
    [[ "$TARGET" == "device" ]] && simulator=()
    (cd "$ROOT/flutter/app" &&
      fvm flutter build ios --config-only "--$mode" "${simulator[@]}" \
        --dart-define=BENCH_API_BASE_URL="$IOS_API_BASE_URL")
    # xcodebuild rather than `flutter build ios`, so a device build can be
    # signed with BENCH_IOS_TEAM_ID from the environment.
    CONFIG="$(tr '[:lower:]' '[:upper:]' <<< "${mode:0:1}")${mode:1}"
    build_ios_app "$ROOT/flutter/app/ios" Runner \
      -workspace "$ROOT/flutter/app/ios/Runner.xcworkspace" -scheme Runner
    ;;
  flutter/android)
    (cd "$ROOT/flutter/app" &&
      fvm flutter build apk "--$BUILD" \
        --dart-define=BENCH_API_BASE_URL="$ANDROID_API_BASE_URL")
    copy_apk "$ROOT/flutter/app/build/app/outputs/flutter-apk/app-$BUILD.apk"
    ;;
  expo/ios)
    # EXPO_PUBLIC_* reaches the JavaScript: Metro inlines it while bundling,
    # which for a release build happens inside this xcodebuild run.
    export EXPO_PUBLIC_BENCH_API_BASE_URL="$IOS_API_BASE_URL"
    (cd "$ROOT/expo/app" && npx expo prebuild --platform ios --clean)
    workspace="$(ls -d "$ROOT"/expo/app/ios/*.xcworkspace | head -1)"
    scheme="$(first_scheme "$workspace")"
    build_ios_app "$ROOT/expo/app/ios" "$scheme" \
      -workspace "$workspace" -scheme "$scheme"
    ;;
  expo/android)
    export EXPO_PUBLIC_BENCH_API_BASE_URL="$ANDROID_API_BASE_URL"
    (cd "$ROOT/expo/app" && npx expo prebuild --platform android --clean)
    (cd "$ROOT/expo/app/android" && ./gradlew "assemble$CONFIG")
    copy_apk "$ROOT/expo/app/android/app/build/outputs/apk/$BUILD/app-$BUILD.apk"
    ;;
  *)
    echo "No benchmark build for $FRAMEWORK/$PLATFORM yet" >&2
    exit 1
    ;;
esac

echo "Built $OUT"
